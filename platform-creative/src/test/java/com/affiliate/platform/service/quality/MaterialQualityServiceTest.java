package com.affiliate.platform.service.quality;

import com.affiliate.platform.domain.quality.MaterialBenchmark7D;
import com.affiliate.platform.domain.quality.MaterialPerformance7D;
import com.affiliate.platform.domain.quality.MaterialQualityLevel;
import com.affiliate.platform.domain.quality.MaterialQualityResult;
import com.affiliate.platform.event.DomainEvent;
import com.affiliate.platform.event.EventPublisher;
import com.affiliate.platform.repository.quality.InMemoryMaterialBenchmarkRepository;
import com.affiliate.platform.repository.quality.InMemoryMaterialQualityHistoryRepository;
import com.affiliate.platform.service.quality.impl.MaterialQualityTagRecommendEngineImpl;
import com.affiliate.platform.tenant.TenantContext;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

@DisplayName("素材质量打标应用服务生命周期与事件发布测试")
class MaterialQualityServiceTest {

    private InMemoryMaterialBenchmarkRepository benchmarkRepo;
    private InMemoryMaterialQualityHistoryRepository historyRepo;
    private MaterialQualityTagRecommendEngine recommendEngine;
    private MaterialQualityService qualityService;
    private List<DomainEvent> publishedEvents;

    @BeforeEach
    void setUp() {
        TenantContext.set("tenant_unit_test");
        benchmarkRepo = new InMemoryMaterialBenchmarkRepository();
        historyRepo = new InMemoryMaterialQualityHistoryRepository();
        recommendEngine = new MaterialQualityTagRecommendEngineImpl();
        publishedEvents = new ArrayList<>();

        EventPublisher testPublisher = publishedEvents::add;
        qualityService = new MaterialQualityService(benchmarkRepo, historyRepo, recommendEngine, testPublisher);
    }

    @AfterEach
    void tearDown() {
        TenantContext.set(null);
    }

    @Test
    @DisplayName("测试首次无基准线时自动生成默认基准并完成评级与事件发布")
    void testEvaluateWithAutoGeneratedBenchmark() {
        MaterialPerformance7D perf = new MaterialPerformance7D(
                "cr_101",
                "cr_101",
                "Test Star Video",
                "AD_cr_101",
                LocalDate.of(2026, 10, 14),
                BigDecimal.valueOf(1200.00),
                30000,
                1200,
                350,
                BigDecimal.valueOf(2640.00) // ROAS = 2.20
        );

        MaterialQualityResult result = qualityService.evaluateAndRecord(perf);

        assertNotNull(result);
        assertEquals("cr_101", result.creativeId());
        assertEquals(MaterialQualityLevel.STAR, result.qualityLevel());

        // 验证已落盘至历史记录仓储
        List<MaterialQualityResult> history = qualityService.getHistory("cr_101", 10);
        assertEquals(1, history.size());
        assertEquals(result.id(), history.getFirst().id());

        // 验证领域事件是否成功发布
        assertEquals(1, publishedEvents.size());
        DomainEvent event = publishedEvents.getFirst();
        assertEquals("creative.quality.tagged.v1", event.eventType());
        assertEquals("tenant_unit_test", event.tenantId());
        assertEquals("cr_101", event.aggregateId());
    }

    @Test
    @DisplayName("测试更新7日基准线并广播基准更新领域事件")
    void testSaveBenchmarkAndEvent() {
        MaterialBenchmark7D customBm = new MaterialBenchmark7D(
                "bm_20261014",
                "tenant_unit_test",
                LocalDate.of(2026, 10, 14),
                LocalDate.of(2026, 10, 8),
                LocalDate.of(2026, 10, 14),
                500,
                BigDecimal.valueOf(120.00),
                60L,
                8L,
                BigDecimal.valueOf(2.00),
                BigDecimal.valueOf(1.00),
                BigDecimal.valueOf(1000.00),
                BigDecimal.valueOf(3.50),
                BigDecimal.valueOf(0.035),
                BigDecimal.valueOf(0.150),
                Instant.now()
        );

        MaterialBenchmark7D saved = qualityService.saveBenchmark(customBm);

        assertNotNull(saved);
        assertEquals("bm_20261014", saved.id());

        // 验证领域事件
        assertEquals(1, publishedEvents.size());
        DomainEvent event = publishedEvents.getFirst();
        assertEquals("creative.benchmark.updated.v1", event.eventType());
        assertEquals("bm_20261014", event.aggregateId());

        // 验证获取最新基准
        MaterialBenchmark7D latest = qualityService.getLatestBenchmark();
        assertEquals(saved.id(), latest.id());
    }

    @Test
    @DisplayName("测试按等级和日期筛选打标列表")
    void testListByLevel() {
        LocalDate today = LocalDate.of(2026, 10, 14);

        // 提交一个 STAR 素材
        MaterialPerformance7D starPerf = new MaterialPerformance7D(
                "cr_star", "cr_star", "Star Item", "AD_cr_star", today,
                BigDecimal.valueOf(1000.00), 20000, 800, 300, BigDecimal.valueOf(2500.00)
        );
        qualityService.evaluateAndRecord(starPerf);

        // 提交一个 BLACKHOLE 素材
        MaterialPerformance7D blackholePerf = new MaterialPerformance7D(
                "cr_bh", "cr_bh", "BH Item", "AD_cr_bh", today,
                BigDecimal.valueOf(1000.00), 10000, 200, 50, BigDecimal.valueOf(300.00)
        );
        qualityService.evaluateAndRecord(blackholePerf);

        List<MaterialQualityResult> starList = qualityService.listByLevel(MaterialQualityLevel.STAR, today);
        assertEquals(1, starList.size());
        assertEquals("cr_star", starList.getFirst().creativeId());

        List<MaterialQualityResult> bhList = qualityService.listByLevel(MaterialQualityLevel.BLACKHOLE, today);
        assertEquals(1, bhList.size());
        assertEquals("cr_bh", bhList.getFirst().creativeId());

        List<MaterialQualityResult> riskList = qualityService.listByLevel(MaterialQualityLevel.RISK, today);
        assertTrue(riskList.isEmpty());
    }
}
